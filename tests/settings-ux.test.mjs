import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { upgrade } from '../src/config.mjs';
import { loadPlaywright } from '../src/browser.mjs';
const root = path.resolve(import.meta.dirname, '..');

test('Settings guides discovery, cross-tab edits, private review, discard and safe save recovery', {skip:process.env.FC_BROWSER_TESTS!=='1'}, async t => {
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'outreach-settings-ux-'));
 const seed=upgrade({}); seed.profiles.forEach(profile=>profile.autoReconnect=false);
 await fs.writeFile(path.join(dir,'state.json'),JSON.stringify(seed));
 const port=14695,url=`http://127.0.0.1:${port}`;
 const child=spawn(process.execPath,[path.join(root,'src/server.mjs')],{cwd:root,env:{...process.env,PORT:String(port),FC_DATA_DIR:dir,FC_FIREBASE_DISABLE:'1',FC_MONITOR_ENABLED:'0',FC_OPEN_TRACKING_ENABLED:'0',FC_REPLY_CAPTURE_ENABLED:'0',FC_REPLY_AUTO:'0'},stdio:['ignore','ignore','pipe']});
 let errors='',browser;child.stderr.on('data',chunk=>errors+=chunk);
 t.after(async()=>{await browser?.close();if(child.exitCode===null){const done=once(child,'exit');child.kill('SIGTERM');await done;}await fs.rm(dir,{recursive:true,force:true});});
 for(let i=0;i<100;i++){if(child.exitCode!==null)throw new Error(errors);try{if((await fetch(url+'/api/state')).ok)break;}catch{}await new Promise(r=>setTimeout(r,50));}
 const api=async(route,data)=>{const res=await fetch(url+'/api/'+route,data===undefined?{}:{method:'POST',headers:{'Content-Type':'application/json','X-FC-Request':'1'},body:JSON.stringify(data)});const value=await res.json();if(!res.ok)throw new Error(value.error);return value;};
 browser=await loadPlaywright().chromium.launch({channel:process.env.FC_TEST_BROWSER_CHANNEL||'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1050}});const browserErrors=[];page.on('pageerror',error=>browserErrors.push(error.message));
 await page.goto(url+'/#settings');
 await page.waitForFunction(()=>document.querySelector('#minSeconds').value!=='');
 assert(await page.locator('#saveSettings').isDisabled());
 const initial=await api('state');
 await page.getByRole('tab',{name:'Eligibility & checks',exact:true}).click();
 await page.locator('#templateChecksEnabled').uncheck();
 await page.locator('#settingsFind').fill('promotional');
 await page.locator('.settings-find-results').getByRole('button',{name:/Promotional claims check/}).click();
 await page.waitForFunction(()=>document.activeElement.id==='templateChecksEnabled');
 assert.equal(await page.locator('#templateChecksEnabled').isChecked(),false);
 await page.locator('#templateChecksEnabled').check();
 await page.locator('#settingsFind').fill('empty queue');
 await page.locator('.settings-find-results').getByRole('button',{name:/Empty queue check interval/}).click();
 await page.waitForFunction(()=>document.activeElement.id==='pollSeconds');
 assert(await page.locator('.pace-empty-queue').evaluate(el=>el.open));
 await page.locator('#settingsFind').fill('PC ID');
 await page.locator('.settings-find-results').getByRole('button',{name:/This PC’s tracking ID/}).click();
 await page.locator('#trackingPcId').waitFor({state:'visible'});
 await page.waitForFunction(()=>document.activeElement.id==='trackingPcId');
 await page.locator('#trackingPcId').fill('4');
 await page.locator('#settingsFind').fill('hourly limit');
 await page.locator('.settings-find-results').getByRole('button',{name:/Hourly limit/}).click();
 await page.waitForFunction(()=>document.activeElement.id==='hourlyCap');
 await page.locator('#hourlyCap').fill('17');
 await page.getByRole('tab',{name:'Eligibility & checks',exact:true}).click();
 await page.locator('#requireActive').uncheck();
 await page.getByRole('tab',{name:'Team coordination',exact:true}).click();
 await page.locator('#teamToken').fill('PRIVATE-REPLACEMENT-TOKEN');
 await page.locator('#teamUrl').fill('https://user:PRIVATE-PASSWORD@example.invalid/coordinator?token=PRIVATE-QUERY');
 await page.getByRole('tab',{name:'Appearance',exact:true}).click();
 const context=page.getByLabel('Show workspace context',{exact:true});await context.uncheck();
 assert(await page.locator('#saveSettings').isVisible());
 assert.match(await page.locator('.settings-draft-status').innerText(),/5 unsaved changes/);
 await page.locator('#settingsReviewChanges').click();
 const drawer=page.getByRole('dialog',{name:'Review settings edits',exact:true});await drawer.waitFor({state:'visible'});
 assert.match(await drawer.innerText(),/17 per hour/);
 assert.match(await drawer.innerText(),/Replacement token entered/);
 assert.doesNotMatch(await drawer.innerText(),/PRIVATE-REPLACEMENT|PRIVATE-PASSWORD|PRIVATE-QUERY/);
 await drawer.getByRole('button',{name:'Discard edits',exact:true}).click();
 const confirm=page.getByRole('dialog',{name:'Discard settings edits?',exact:true});
 await confirm.getByRole('button',{name:'Cancel',exact:true}).click();assert(await drawer.isVisible());
 assert.equal(await page.locator('#teamToken').inputValue(),'PRIVATE-REPLACEMENT-TOKEN');
 await drawer.getByRole('button',{name:'Discard edits',exact:true}).click();await confirm.getByRole('button',{name:'Discard edits',exact:true}).click();
 assert.equal(await drawer.isVisible(),false);
 assert.equal(await page.locator('#hourlyCap').inputValue(),String(initial.settings.pacing.hourlyCap));
 assert.equal(await page.locator('#teamToken').inputValue(),'');
 assert.equal(await context.isChecked(),false);
 assert.equal(await page.locator('#saveSettings').isVisible(),false);
 await page.locator('#settingsFind').fill('not a real setting xyz');assert.match(await page.locator('.settings-find-results').innerText(),/0 matching settings/);
 await page.getByRole('button',{name:'Clear search',exact:true}).click();
 await page.getByRole('tab',{name:'Sending pace',exact:true}).click();await page.locator('#hourlyCap').fill('17');
 await page.getByRole('tab',{name:'Eligibility & checks',exact:true}).click();await page.locator('#requireActive').uncheck();
 // An unrelated saved field changes in another window while the local draft remains mounted.
 const external=structuredClone((await api('state')).settings);external.pacing.dailyCap=77;
 await api('settings',{settings:external});await page.waitForTimeout(1900);
 assert.equal(await page.locator('#dailyCap').inputValue(),String(initial.settings.pacing.dailyCap));
 await page.route('**/api/settings',route=>route.fulfill({status:400,contentType:'application/json',body:JSON.stringify({error:'Synthetic save rejection'})}));
 await page.locator('#settingsReviewChanges').click();await drawer.getByRole('button',{name:'Save reviewed changes',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#settingsSaveFeedback').textContent.includes('Synthetic save rejection'));
 assert.equal(await page.locator('#hourlyCap').inputValue(),'17');assert.equal(await page.locator('#requireActive').isChecked(),false);
 assert(await drawer.isVisible());
 await page.unroute('**/api/settings');
 await drawer.getByRole('button',{name:'Save reviewed changes',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#settingsSaveFeedback').textContent.includes('now active on this PC'));
 const saved=await api('state');assert.equal(saved.settings.pacing.hourlyCap,17);assert.equal(saved.settings.pacing.dailyCap,77);assert.equal(saved.settings.eligibility.requireActive,false);
 assert.equal(saved.settings.tracking.pcId,initial.settings.tracking.pcId);
 assert.match(await drawer.innerText(),/No unsaved configuration changes/);
 await drawer.getByRole('button',{name:'Back to settings',exact:true}).click();
 assert(await page.locator('#saveSettings').isDisabled());
 // Review and search remain usable on both viewport sizes, with the shared sticky stack.
 await page.getByRole('tab',{name:'Sending pace',exact:true}).click();await page.locator('#hourlyCap').fill('18');
 assert(await page.locator('#notice').isHidden());
 for(const width of [1440,390]) {
  await page.setViewportSize({width,height:1050});
  assert(await page.locator('.app-viewport').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  if(process.env.FC_UI_SCREENSHOT_DIR){await fs.mkdir(process.env.FC_UI_SCREENSHOT_DIR,{recursive:true});await page.screenshot({path:path.join(process.env.FC_UI_SCREENSHOT_DIR,`settings-${width}.png`)});}
  await page.locator('#settingsReviewChanges').click();assert(await drawer.evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  if(process.env.FC_UI_SCREENSHOT_DIR)await page.screenshot({path:path.join(process.env.FC_UI_SCREENSHOT_DIR,`settings-review-${width}.png`)});
  await drawer.getByRole('button',{name:'Back to settings',exact:true}).click();
 }
 assert.deepEqual(browserErrors,[]);
});
